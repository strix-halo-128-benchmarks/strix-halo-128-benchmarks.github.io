#!/usr/bin/env bash
# Publish the site from the measurement pipeline: regenerate, and push only if the data changed.
# Runs from a systemd user timer. Never invents content — build.sh regenerates from ~/docs, ~/runs
# and ~/llama-local, and refuses to publish if any identifier survives its sanitising pass.
set -euo pipefail

REPO="$HOME/strix-halo-benchmarks"
LOG_DIR="$HOME/.local/state/strix-halo-benchmarks"
mkdir -p "$LOG_DIR"

export PATH="$HOME/.local/bin:/usr/local/bin:/usr/bin:/bin"
export GIT_AUTHOR_NAME='Strix Halo Benchmarks'
export GIT_AUTHOR_EMAIL='strix-halo-bench@users.noreply.github.com'
export GIT_COMMITTER_NAME="$GIT_AUTHOR_NAME"
export GIT_COMMITTER_EMAIL="$GIT_AUTHOR_EMAIL"

cd "$REPO"

# Never publish mid-measurement: a run in flight has written its identity and perf rows but not its
# capability rows, so building now would commit a row that looks unmeasured. A bench unit is the
# reliable signal (the harness always runs under bench-*), and a fresh run file is the backstop for a
# manual run outside systemd.
if systemctl --user list-units --state=active --no-legend 'bench-*' | grep -q bench; then
    echo "skip: a bench unit is active — $(systemctl --user list-units --state=active --no-legend 'bench-*' | awk '{print $1}' | paste -sd' ')"
    exit 0
fi
NEWEST=$(find "$HOME/runs" -maxdepth 1 -name '2026*.jsonl' -newermt '-15 minutes' -print -quit 2>/dev/null || true)
if [ -n "$NEWEST" ]; then
    echo "skip: run file written in the last 15 minutes ($(basename "$NEWEST")) — measurement may still be finishing"
    exit 0
fi
# A harness can also be launched detached (a background shell job with persist_on_release) instead of
# as a bench-* unit. Then no unit is active and its run file age past 15 minutes while the later axes
# are still going — round-6 sat on MMLU-Pro for two hours after writing its identity/perf/HumanEval
# rows. Match the harness processes themselves; they outlive both signals above.
if pgrep -f 'complete-round[0-9]+\.py|bench/t20\.py|bench/mmlu_pro\.py|bench/humaneval\.py' >/dev/null 2>&1; then
    echo "skip: a bench harness process is alive — $(pgrep -af 'complete-round[0-9]+\.py|bench/t20\.py|bench/mmlu_pro\.py|bench/humaneval\.py' | cut -c1-90 | paste -sd'; ')"
    exit 0
fi

echo "=== $(date -Is) regenerate"
./scripts/build.sh

if git diff --quiet && git diff --cached --quiet; then
    echo "no change — nothing to publish"
    exit 0
fi

echo "=== changes:"
git status --porcelain
git add -A
git commit -q -m "Refresh measurements ($(date +%Y-%m-%d))

Regenerated by scripts/build.sh from the run catalogue; only published if the
data actually changed."
git push -q origin main
echo "=== pushed $(git rev-parse --short HEAD)"
